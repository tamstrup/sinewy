export const messages = { en, da }

export function translate(language, locale, key, params = {}) {
  let message = messages[language]?.[key] ?? en[key]
  if (!message) throw new Error(`Unknown translation key: ${key}`)
  if (typeof message === 'object') {
    if (!plurals.has(language)) plurals.set(language, new Intl.PluralRules(language))
    message = message[plurals.get(language).select(params.count)] ?? message.other
  }
  return message.replace(/\{(\w+)\}/g, (_, name) => {
    if (!(name in params)) throw new Error(`Missing translation parameter: ${key}.${name}`)
    return typeof params[name] === 'number' ? formatNumber(params[name], locale) : params[name]
  })
}
