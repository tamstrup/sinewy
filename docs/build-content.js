import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { compileDocument } from './markdown.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const components = path.join(root, 'docs', 'components')
const output = path.join(root, 'docs', 'content.generated.js')

export async function buildDocuments() {
  const files = (await fs.readdir(components))
    .filter(file => file.endsWith('.md') && file.toLowerCase() !== 'readme.md')
    .sort()

  return Promise.all(files.map(async file => {
    const sourcePath = path.join(components, file)
    return compileDocument(await fs.readFile(sourcePath, 'utf8'), sourcePath, root)
  }))
}

export function contentModule(documents) {
  return `// Generated by docs/build-content.js. Do not edit directly.\n\nconst documents = ${JSON.stringify(documents, null, 2)}\n\nconst documentsBySlug = Object.fromEntries(documents.map(document => [document.slug, document]))\n\nexport { documents, documentsBySlug }\nexport default documents\n`
}

export async function buildContent() {
  const source = contentModule(await buildDocuments())
  await fs.writeFile(output, source)
  return source
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  await buildContent()
